#!/usr/bin/env python3
"""
Regenerate src/font_data.hpp — an embedded, subsetted, gzip-compressed font.

The UI only needs a handful of glyph ranges; subsetting keeps the embedded
blob a few hundred KB instead of the full multi-MB variable font.  The
resulting bytes are loaded at runtime with ImGui's
AddFontFromMemoryCompressedTTF, so the font is always available on every OS.

Requires:  pip install fonttools brotli
Usage:     python3 packaging/make-font-header.py [path-to-JuliaMonoSiesta-Regular.ttf]
"""
import gzip
import sys
from pathlib import Path

# Unicode ranges the kopi UI actually renders: Latin scripts, Greek, Cyrillic,
# currency, general punctuation (…), arrows (→), box/geometric shapes, misc
# symbols, and dingbats (✓).
UNICODES = (
    "U+0000-00FF,U+0100-024F,U+0370-03FF,U+0400-04FF,U+20A0-20CF,"
    "U+2000-206F,U+2190-21FF,U+2500-257F,U+25A0-25FF,U+2600-26FF,U+2700-27BF"
)

SRC_DEFAULT = Path.home() / ".local/share/fonts/JuliaMonoSiesta-Regular.ttf"
OUT_HEADER = Path(__file__).resolve().parent.parent / "src/font_data.hpp"


def main() -> int:
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else SRC_DEFAULT
    if not src.exists():
        print(f"error: font not found: {src}", file=sys.stderr)
        return 1

    import fontTools.subset as subset  # noqa: F401 (ensures pyftsubset works)
    from subprocess import run

    subset_ttf = Path("/tmp/juliasubset.ttf")
    run(["pyftsubset", str(src),
         "--unicodes=" + UNICODES,
         "--layout-features=*",
         "--name-IDs=*",
         f"--output-file={subset_ttf}"], check=True)

    data = gzip.compress(subset_ttf.read_bytes(), compresslevel=9)

    lines = []
    for i in range(0, len(data), 16):
        chunk = data[i:i + 16]
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in chunk) + ",")

    header = f"""// Auto-generated by packaging/make-font-header.py — do not edit by hand.
//
// JuliaMonoSiesta (Regular), subsetted to the glyphs the UI renders and
// gzip-compressed, for embedding so the font is available on every OS.
// Regenerate with:  python3 packaging/make-font-header.py

#pragma once

#include <cstddef>

namespace kopi_font {{

/// Gzip-compressed, subsetted JuliaMonoSiesta-Regular.ttf.
static const unsigned char g_font_compressed[] = {{
{body}
}};

static const std::size_t g_font_compressed_size = sizeof(g_font_compressed);

}} // namespace kopi_font
""".format(body="\n".join(lines))

    OUT_HEADER.write_text(header)
    print(f"wrote {OUT_HEADER} ({len(data)} compressed bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
