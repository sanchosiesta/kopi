#!/usr/bin/env python3
"""
Regenerate src/font_data.hpp — an embedded, subsetted, stb_compress-compressed
font.

The UI only needs a handful of glyph ranges; subsetting keeps the embedded
blob a few hundred KB instead of the full multi-MB variable font.  The bytes
are stb_compress-compressed (the format ImGui's AddFontFromMemoryCompressedTTF
expects) and loaded at runtime, so the font is always available on every OS.

Requires:  pip install fonttools brotli
           g++ (to compile ImGui's binary_to_compressed_c.cpp)

Usage:     python3 packaging/make-font-header.py [path-to-JuliaMonoSiesta-Regular.ttf]
"""
import re
import subprocess
import sys
import urllib.request
from pathlib import Path

# Unicode ranges the kopi UI actually renders: Latin scripts, Greek, Cyrillic,
# currency, general punctuation (…), arrows (→), box/geometric shapes, misc
# symbols, and dingbats (✓).
UNICODES = (
    "U+0000-00FF,U+0100-024F,U+0370-03FF,U+0400-04FF,U+20A0-20CF,"
    "U+2000-206F,U+2190-21FF,U+2500-257F,U+25A0-25FF,U+2600-26FF,U+2700-27BF"
)

SRC_DEFAULT = Path.home() / ".local/share/fonts/JuliaMonoSiesta-Regular.ttf"
OUT_HEADER = Path(__file__).resolve().parent.parent / "src/font_data.hpp"

# ImGui's converter lives in the imgui repo; try a local checkout first.
IMGUI_FONTS = [
    Path("build/_deps/imgui-src/misc/fonts/binary_to_compressed_c.cpp"),
    Path("redhat-linux-build/_deps/imgui-src/misc/fonts/binary_to_compressed_c.cpp"),
]
B2C_URL = ("https://raw.githubusercontent.com/ocornut/imgui/"
           "v1.91.9/misc/fonts/binary_to_compressed_c.cpp")


def find_b2c() -> Path:
    for p in IMGUI_FONTS:
        if p.exists():
            return p
    # Fall back to downloading the converter source.
    print("binary_to_compressed_c.cpp not found locally — downloading from imgui")
    target = Path("/tmp/binary_to_compressed_c.cpp")
    urllib.request.urlretrieve(B2C_URL, target)
    return target


def main() -> int:
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else SRC_DEFAULT
    if not src.exists():
        print(f"error: font not found: {src}", file=sys.stderr)
        return 1

    subprocess.run(["pyftsubset", str(src),
                    "--unicodes=" + UNICODES,
                    "--layout-features=*",
                    "--name-IDs=*",
                    "--output-file=/tmp/juliasubset.ttf"], check=True)

    # Compile + run ImGui's converter to stb_compress-compress the font.
    b2c = find_b2c()
    subprocess.run(["g++", str(b2c), "-o", "/tmp/b2c"], check=True)
    out = subprocess.run(["/tmp/b2c", "-u8", "/tmp/juliasubset.ttf",
                          "g_font_compressed"], capture_output=True, text=True)
    if out.returncode != 0:
        print(out.stderr, file=sys.stderr)
        return 1

    # Parse the generated array body.
    body = re.search(r"\{([^}]*)\}", out.stdout, re.S).group(1)
    bytes_ = [int(x) for x in re.findall(r"\d+", body)]

    lines = []
    for i in range(0, len(bytes_), 12):
        chunk = bytes_[i:i + 12]
        lines.append("    " + ", ".join(str(b) for b in chunk) + ",")

    header = """// Auto-generated by packaging/make-font-header.py — do not edit by hand.
//
// JuliaMonoSiesta (Regular), subsetted to the glyphs the UI renders and
// stb_compress-compressed (the format ImGui's AddFontFromMemoryCompressedTTF
// expects), for embedding so the font is available on every OS.
// Regenerate with:  python3 packaging/make-font-header.py

#pragma once

#include <cstddef>

namespace kopi_font {

/// stb_compress-compressed, subsetted JuliaMonoSiesta-Regular.ttf.
static const unsigned char g_font_compressed[] = {
__BODY__
};

static const std::size_t g_font_compressed_size = sizeof(g_font_compressed);

} // namespace kopi_font
""".replace("__BODY__", "\n".join(lines))

    OUT_HEADER.write_text(header)
    print(f"wrote {OUT_HEADER} ({len(bytes_)} compressed bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
